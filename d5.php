    <h4>La Corniche, le meilleur des deux mondes</h4>
    <br><br>
    <p>
    Votre prochain arrêt est à 6 km, la "Corniche". Une belle promenade sociale dans 
    le quartier d'Ain-Diab et un lieu où le rythme énergétique de Casablanca est à son apogée.<br>
    Amateurs de la ''night life'', vous allez apprécier la variété des clubs, des bars, 
    des restaurants sur mer et des discothèques alignés pour tous les goûts. En 
    d'autres termes, la corniche s'imprègne de tout le dynamisme et l'énergie pure casablancaise.<br>
    Par ailleurs, si vous avez plus l'âme d'un aventurier, vous pouvez opter pour une variété 
    d'activités nautiques durant la journée. Entre surf, Planche à voile, Jet ski ou plongé 
    maritime, embarquez dans une aventure en mer avec une sélection de sports conçus pour tous 
    les niveaux <br>
    </p>
    <br><br>
