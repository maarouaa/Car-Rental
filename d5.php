    <h4>Morocco Mall, un temple du shopping et du divertissement </h4>
    <br><br>
    <p>
    Que serait un voyage sans shopping ? Vous ne manquerez sans doute pas, l'un des 
    plus grands centres commerciaux du continent Africain, le Morocco Mall.<br>
    En effet, le centre en question dispose d'un grand choix d'enseignes célèbres 
    par exemple, Zara, Dior, Adidas, Armani , Bershka… ainsi qu'une panoplie de 
    divertissements, alliant, L'Imax pour les cinéphiles, Aquadream pour les fans 
    des mystères maritimes, Adventureland pour le fun en famille et bien plus.<br>
    Aujourd'hui, le Morocco Mall est un centre commercial qui parade son attraction 
    touristique à la vue de tous les amoureux du shopping et du divertissement.<br>
    </p>
