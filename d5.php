    <h4>Casablanca : 3 Lieux incontournables à visiter en voiture</h4>
    <p>Casablanca est une ville marocaine au patrimoine architectural unique, mêlant modernité et 
        tradition. Située sur la côte atlantique du pays, la ville mélange un mode de vie 
        cosmopolite, moderne et énergétique avec un sens envoûtant de l'art et de l'histoire. 
        Découvrez 3 lieux touristiques à visiter dans une ville aux facettes multiples.
    <br><br>
    <b>L'effet du film '' Casablanca ''</b>
    <br><br>
    Le film produit par Michael Curtiz, le film Casablanca se déroule durant la 
    Seconde Guerre mondiale. Une histoire dramatique entre Rick et Ilsa, mettant 
    en scène deux personnages déchirés entre l'amour et le devoir. Le film connaît 
    un énorme succès en 1940 et est à ce jour, l'une des plus grandes figures de la Pop Culture.<br>
    La ville de Casablanca est toujours associée au flair romantique du célèbre film et la 
    fiction est devenue réalité. En effet, chaque année des millions de touristes et de curieux 
    viennent encore découvrir la mégalopole exaltante.
    <br><br>
    <h4>La mosquée Hassan 2, un chef-d'oeuvre historique</h4>
    <br><br>
    Vous n'échapperez pas à la beauté de l'architecture minutieuse de la 
    mosquée Hassan 2, qui rayonne dans le ciel de Casablanca. Notamment, 
    avec le plus haut minaret monde atteignant les 210m, une salle de 
    prière aux proportions titanesques couvrant 
    20.000 m² et une capacité d'accueil de plus 25.000 personnes.
    <br>
    La mosquée Hassan 2 est avant tout le fruit de l'effort de feu Sa Majesté le roi 
    Hassan II et de plus de 12.000 personnes qui ont contribué à la construction de 
    l'édifice religieux. Ainsi, le complexe dispose d'une grande bibliothèque, une école 
    d'artisanat, un musée historique, un bain de vapeur et bien plus. 
    Le tout est bâti sur les roches de l'océan Atlantique.
    <br>
    Sublimement finalisés par des artisans de tous les coins du Maroc. Aujourd'hui le chef-d'oeuvre
    se hisse parmi les grands monuments islamiques et inspire l'émerveillement des touristes à
    travers le globe. Vous pouvez à tout moment vivre l'expérience artisanale marocaine de la 
    mosquée Hassan II avec 
    des visites guidées et organisées au quotidien, sauf le vendredi et l'heure de la prière.
    </p>
    <br><br>
